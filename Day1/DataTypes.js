// string - used to store text values
var studentName="Saichand";
console.log(studentName);
console.log(typeof studentName);

// number - used to store numeric values
var studentAge=30;
console.log(studentAge);
console.log(typeof studentAge);

// boolean - used to store true or false values
var isStudent=true;
console.log(isStudent);
console.log(typeof isStudent);

// undefined - used to represent a variable that has been declared but not assigned a value
var phoneNumber;
console.log(phoneNumber);
console.log(typeof phoneNumber);

// null - used to represent the intentional absence of any object value
var address=null;
console.log(address);
console.log(typeof address);

// BigInt - used to represent large integers that cannot be represented by the number data type
var accountNumber=9876543210987654321n;
console.log(accountNumber);
console.log(typeof accountNumber);

// maximum safe integer - the largest integer that can be safely represented by the number data type
var number=Number.MAX_SAFE_INTEGER;
console.log(number);
console.log(typeof number); 
